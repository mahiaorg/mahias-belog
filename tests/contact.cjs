const fs = require('fs');
const vm = require('vm');
const assert = require('assert');
const script = fs.readFileSync(require('path').resolve(__dirname, '../script.js'), 'utf8');
const code = script.slice(script.indexOf('(function initContact()'), script.indexOf('const year ='));
const feedback = { textContent: '' };
let submit;
const elements = { name: { value: '  Test & Name  ' }, email: { value: 'hello@example.com' }, message: { value: 'Hello & welcome?\nSecond line' } };
const form = { elements, reportValidity: () => true, addEventListener: (type, handler) => { submit = handler; } };
const location = { href: '' };
vm.runInNewContext(code, { document: { getElementById: id => id === 'contact-form' ? form : feedback }, window: { location } });
submit({ preventDefault() {} });
const url = new URL(location.href);
assert.equal(url.protocol, 'mailto:');
assert.equal(url.searchParams.get('subject'), 'Portfolio enquiry from Test & Name');
assert(url.searchParams.get('body').startsWith(elements.message.value));
assert.equal(elements.message.value, 'Hello & welcome?\nSecond line');
assert(!feedback.textContent.includes('Message Sent'));
location.href = ''; form.reportValidity = () => false;
submit({ preventDefault() {} });
assert.equal(location.href, '');
console.log('PASS: contact validation, URL encoding and preservation of message text; no email sent.');
